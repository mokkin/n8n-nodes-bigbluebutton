import type { INodePropertyOptions } from 'n8n-workflow';

function toOptions(values: string[]): INodePropertyOptions[] {
	return values.map((value) => ({
		name: value.replace(/([a-z0-9])([A-Z])/g, '$1 $2').replace(/^./, (char) => char.toUpperCase()),
		value,
	}));
}

